
package com.shadowbase.service;

import org.springframework.stereotype.Service;
import org.testcontainers.containers.PostgreSQLContainer;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Map;

@Service
public class EnvironmentService {

    private PostgreSQLContainer<?> sourcePostgres;
    private PostgreSQLContainer<?> targetPostgres;

    public Map<String, String> startEnvironment() {

        if (sourcePostgres != null && sourcePostgres.isRunning()
                && targetPostgres != null && targetPostgres.isRunning()) {

            return Map.of(
                    "status", "already_running",
                    "message", "Source and target databases are already running",
                    "sourceContainerId", sourcePostgres.getContainerId(),
                    "targetContainerId", targetPostgres.getContainerId(),
                    "sourceJdbcUrl", sourcePostgres.getJdbcUrl(),
                    "targetJdbcUrl", targetPostgres.getJdbcUrl()
            );
        }

        stopContainers();

        try {
            sourcePostgres = new PostgreSQLContainer<>("postgres:16-alpine")
                    .withDatabaseName("source_db")
                    .withUsername("shadowbase")
                    .withPassword("shadowbase");

            targetPostgres = new PostgreSQLContainer<>("postgres:16-alpine")
                    .withDatabaseName("target_db")
                    .withUsername("shadowbase")
                    .withPassword("shadowbase");

            sourcePostgres.start();
            targetPostgres.start();

            return Map.of(
                    "status", "started",
                    "message", "Source and target databases started successfully",
                    "sourceContainerId", sourcePostgres.getContainerId(),
                    "targetContainerId", targetPostgres.getContainerId(),
                    "sourceJdbcUrl", sourcePostgres.getJdbcUrl(),
                    "targetJdbcUrl", targetPostgres.getJdbcUrl()
            );

        } catch (Exception e) {
            stopContainers();

            throw new RuntimeException(
                    "Failed to start source and target databases: "
                            + e.getMessage(), e
            );
        }
    }

    public String seedEnvironment() {

        if (sourcePostgres == null || !sourcePostgres.isRunning()
                || targetPostgres == null || !targetPostgres.isRunning()) {

            return "Start both databases first";
        }

        try {
            // SOURCE DATABASE: Complete schema
            try (
                    Connection connection = DriverManager.getConnection(
                            sourcePostgres.getJdbcUrl(),
                            sourcePostgres.getUsername(),
                            sourcePostgres.getPassword()
                    );
                    Statement statement = connection.createStatement()
            ) {

                statement.execute("""
                        CREATE TABLE IF NOT EXISTS customers (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL,
                            email VARCHAR(150) UNIQUE NOT NULL
                        )
                        """);

                statement.execute("""
                        CREATE TABLE IF NOT EXISTS products (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            sku VARCHAR(50) UNIQUE NOT NULL,
                            name VARCHAR(100) NOT NULL,
                            price NUMERIC(10,2) NOT NULL
                        )
                        """);

                statement.execute("""
                        CREATE TABLE IF NOT EXISTS orders (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            order_reference VARCHAR(50) UNIQUE NOT NULL,
                            customer_id BIGINT REFERENCES customers(id),
                            product_id BIGINT REFERENCES products(id),
                            quantity INTEGER NOT NULL,
                            total NUMERIC(10,2) NOT NULL
                        )
                        """);
            }

            // TARGET DATABASE: Older schema
            try (
                    Connection connection = DriverManager.getConnection(
                            targetPostgres.getJdbcUrl(),
                            targetPostgres.getUsername(),
                            targetPostgres.getPassword()
                    );
                    Statement statement = connection.createStatement()
            ) {

                statement.execute("""
                        CREATE TABLE IF NOT EXISTS customers (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL
                        )
                        """);

                statement.execute("""
                        CREATE TABLE IF NOT EXISTS products (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            sku VARCHAR(50) UNIQUE NOT NULL,
                            name VARCHAR(100) NOT NULL
                        )
                        """);

                statement.execute("""
                        CREATE TABLE IF NOT EXISTS orders (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            order_reference VARCHAR(50) UNIQUE NOT NULL,
                            customer_id BIGINT,
                            quantity INTEGER NOT NULL,
                            total NUMERIC(10,2) NOT NULL
                        )
                        """);
            }

            return "Both databases seeded successfully. "
                    + "Source has the complete schema; target has the older schema.";

        } catch (Exception e) {
            throw new RuntimeException(
                    "Database seeding failed: " + e.getMessage(), e
            );
        }
    }

    // Get a connection to the source database
    public Connection getSourceConnection() throws SQLException {

        if (sourcePostgres == null || !sourcePostgres.isRunning()) {
            throw new IllegalStateException(
                    "Source database is not running."
            );
        }

        return DriverManager.getConnection(
                sourcePostgres.getJdbcUrl(),
                sourcePostgres.getUsername(),
                sourcePostgres.getPassword()
        );
    }

    // Get a connection to the target database
    public Connection getTargetConnection() throws SQLException {

        if (targetPostgres == null || !targetPostgres.isRunning()) {
            throw new IllegalStateException(
                    "Target database is not running."
            );
        }

        return DriverManager.getConnection(
                targetPostgres.getJdbcUrl(),
                targetPostgres.getUsername(),
                targetPostgres.getPassword()
        );
    }

    public String stopEnvironment() {

        stopContainers();

        return "Source and target databases stopped successfully";
    }

    private void stopContainers() {

        if (targetPostgres != null) {
            try {
                targetPostgres.stop();
            } catch (Exception ignored) {
                // Continue cleanup even if stopping one container fails.
            } finally {
                targetPostgres = null;
            }
        }

        if (sourcePostgres != null) {
            try {
                sourcePostgres.stop();
            } catch (Exception ignored) {
                // Continue cleanup.
            } finally {
                sourcePostgres = null;
            }
        }
    }
}
